/** Запасные сообщения на дни 31–180 (циклически, с вариациями) */
export function messageForDay(dayNumber: number): BotMessage {
  if (dayNumber <= BOT_MESSAGES.length) return BOT_MESSAGES[dayNumber - 1];
  const base = BOT_MESSAGES[(dayNumber - 1) % BOT_MESSAGES.length];
  return { day: dayNumber, morning: base.morning, evening: base.evening };
}
